import { useCallback, useEffect, useMemo, useRef, useState } from 'react';
import { reanchor } from '../../core/anchors';
import { KIND_LABEL, call, fmtTime, usd, type Boot, type FileEntry, type Folder, type PreviewSummary, type RunResult, type SessionData } from '../api';
import { Compare } from './Compare';
import { Editor, type EditorHandle, type Highlight } from './Editor';
import { ModeToggle, TargetChips } from './common';
import { ReviewModal } from './ReviewModal';

interface Props {
  boot: Boot;
  sessionId: string;
  onChanged(): void;
  notify(msg: string, kind?: 'info' | 'error' | 'ok'): void;
  onBudgetChanged(): void;
  autoGenerate?: boolean;
  onAutoGenerated?(): void;
}

type RightTab = 'comments' | 'recs' | 'insights' | 'rules' | 'history' | 'context';
type Sel = { start: number; end: number; text: string } | null;
type PickKey = string; // `${folderId}|${relPath}`

export function SessionView({ boot, sessionId, onChanged, notify, onBudgetChanged, autoGenerate, onAutoGenerated }: Props) {
  const [data, setData] = useState<SessionData | null>(null);
  const [working, setWorking] = useState('');
  const [saveState, setSaveState] = useState<'saved' | 'saving' | 'unsaved'>('saved');
  const [tab, setTab] = useState<'draft' | 'original' | 'compare'>('draft');
  const [right, setRight] = useState<RightTab>('comments');
  const [sel, setSel] = useState<Sel>(null);
  const [activeComment, setActiveComment] = useState<string | null>(null);
  const [commentDraft, setCommentDraft] = useState('');
  const [instruction, setInstruction] = useState('');
  const [busy, setBusy] = useState(false);
  const [review, setReview] = useState<PreviewSummary | null>(null);
  const [picks, setPicks] = useState<Set<PickKey>>(new Set());
  const [compareLeft, setCompareLeft] = useState<string | undefined>();
  const editorRef = useRef<EditorHandle | null>(null);
  const saveTimer = useRef<number | null>(null);
  const pendingText = useRef<string | null>(null);

  const load = useCallback(async () => {
    const d = await call<SessionData>('sessions:get', { id: sessionId });
    setData(d);
    setWorking(d.workingText);
    pendingText.current = null;
    setSaveState('saved');
    return d;
  }, [sessionId]);

  useEffect(() => {
    setTab('draft');
    setSel(null);
    setPicks(new Set());
    load().catch((e) => notify(e.message, 'error'));
  }, [sessionId, load, notify]);

  const approved = data?.status === 'approved';
  const target = boot.targets.find((t) => t.id === data?.targetId);
  const original = data?.versions[0]?.text ?? '';

  // ----- autosave of the working copy (every edit is persisted; versions are created at meaningful points) -----
  const flush = useCallback(async () => {
    if (saveTimer.current) window.clearTimeout(saveTimer.current);
    saveTimer.current = null;
    const t = pendingText.current;
    if (t === null) return;
    pendingText.current = null;
    setSaveState('saving');
    try {
      await call('sessions:saveWorking', { id: sessionId, text: t });
      setSaveState(pendingText.current === null ? 'saved' : 'unsaved');
    } catch (e: any) {
      setSaveState('unsaved');
      notify(e.message, 'error');
    }
  }, [sessionId, notify]);

  useEffect(() => () => void flush(), [flush]);

  const onEdit = (text: string) => {
    if (approved) return;
    setWorking(text);
    pendingText.current = text;
    setSaveState('unsaved');
    if (saveTimer.current) window.clearTimeout(saveTimer.current);
    saveTimer.current = window.setTimeout(() => void flush(), 500);
  };

  const checkpoint = useCallback(async () => {
    await flush();
    const v = await call<{ seq: number } | null>('sessions:checkpoint', { id: sessionId, note: 'Manual edit (saved)' });
    await load();
    notify(v ? `Saved as version ${v.seq}.` : 'No changes since the last version.', 'ok');
  }, [flush, load, notify, sessionId]);

  useEffect(() => {
    const onKey = (e: KeyboardEvent) => {
      if (e.ctrlKey && e.key.toLowerCase() === 's') {
        e.preventDefault();
        if (!approved) void checkpoint();
      }
    };
    window.addEventListener('keydown', onKey);
    return () => window.removeEventListener('keydown', onKey);
  }, [checkpoint, approved]);

  // ----- comments anchored to text -----
  const anchored = useMemo(() => {
    const m = new Map<string, { start: number; end: number } | null>();
    for (const c of data?.comments ?? []) m.set(c.id, reanchor(working, c.quote, c.start));
    return m;
  }, [data?.comments, working]);

  const highlights: Highlight[] = useMemo(
    () =>
      (data?.comments ?? [])
        .filter((c) => c.status === 'open')
        .flatMap((c) => {
          const a = anchored.get(c.id);
          return a ? [{ id: c.id, start: a.start, end: a.end, title: c.body, active: c.id === activeComment }] : [];
        }),
    [data?.comments, anchored, activeComment],
  );

  const addComment = async () => {
    if (!sel || !commentDraft.trim()) return;
    await flush();
    await call('comments:add', { sessionId, start: sel.start, end: sel.end, quote: sel.text, body: commentDraft.trim() });
    setCommentDraft('');
    await load();
    setRight('comments');
  };

  // ----- generation -----
  const pickList = () => [...picks].map((k) => ({ folderId: k.split('|')[0], relPath: k.slice(k.indexOf('|') + 1) }));

  const startGeneration = async (kind: 'generate' | 'revise', selection: Sel = null) => {
    if (!data) return;
    setBusy(true);
    try {
      await flush();
      const preview = await call<PreviewSummary>('gen:preview', {
        sessionId,
        kind,
        excerpts: pickList(),
        instruction: kind === 'revise' ? instruction : undefined,
        selection: selection ? { start: selection.start, end: selection.end } : null,
      });
      // Anything that would send project file excerpts, or that is blocked, is shown for review first.
      if (preview.excerpts.length > 0 || !preview.canRun) {
        setReview(preview);
        setBusy(false);
        return;
      }
      await runPreview(preview.previewId);
    } catch (e: any) {
      notify(e.message, 'error');
      setBusy(false);
    }
  };

  const runPreview = async (previewId: string) => {
    setBusy(true);
    setReview(null);
    try {
      const r = await call<RunResult>('gen:run', { previewId });
      await load();
      onChanged();
      onBudgetChanged();
      if (r.status === 'ok') {
        setTab('draft');
        setInstruction('');
        notify(r.message, 'ok');
        if (data?.mode === 'challenge') setRight('recs');
        else setRight('insights');
      } else notify(r.message, 'error');
    } catch (e: any) {
      notify(e.message, 'error');
    } finally {
      setBusy(false);
    }
  };

  const updateMeta = async (patch: { title?: string; targetId?: string; mode?: 'preserve' | 'challenge' }) => {
    await call('sessions:update', { id: sessionId, ...patch });
    await load();
    onChanged();
  };

  const restore = async (versionId: string) => {
    await flush();
    const v = await call<{ seq: number }>('sessions:restore', { id: sessionId, versionId });
    await load();
    setTab('draft');
    notify(`Restored as version ${v.seq}. Nothing was deleted.`, 'ok');
  };

  const decideRec = async (id: string, decision: 'accepted' | 'rejected') => {
    await flush();
    await call('recs:decide', { id, decision });
    await load();
    notify(decision === 'accepted' ? 'Recommendation added to the draft as a new version.' : 'Recommendation rejected.', 'ok');
  };

  const approve = async () => {
    await flush();
    let r = await call<{ approved: boolean; missing: string[] }>('sessions:approve', { id: sessionId, force: false });
    if (!r.approved) {
      const ok = window.confirm(
        `These protected rules are no longer in the draft:\n\n- ${r.missing.join('\n- ')}\n\nApprove anyway? (The approval record will note that they were removed.)`,
      );
      if (!ok) return;
      r = await call('sessions:approve', { id: sessionId, force: true });
    }
    await load();
    onChanged();
    notify('Prompt approved. You can now copy it or open the assistant.', 'ok');
  };

  const copy = async (which: 'approved' | 'working') => {
    await flush();
    const n = await call<number>('clipboard:copy', { sessionId, which });
    notify(`Copied ${n.toLocaleString()} characters to the clipboard.`, 'ok');
  };

  // "Create and generate" from the composer starts the first generation once the prompt has loaded.
  const autoStarted = useRef(false);
  useEffect(() => {
    if (autoGenerate && data && !autoStarted.current) {
      autoStarted.current = true;
      onAutoGenerated?.();
      void startGeneration('generate');
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [autoGenerate, data]);

  if (!data || !target) return <div className="empty">Loading…</div>;

  const latestOk = data.generations.find((g) => g.status === 'ok');
  const pendingRecs = data.recommendations.filter((r) => r.status === 'pending').length;
  const openComments = data.comments.filter((c) => c.status === 'open');
  const provider = boot.settings.provider;

  return (
    <div className="session">
      <div className="session-head">
        <input className="title-input" defaultValue={data.title} key={data.id} onBlur={(e) => e.target.value.trim() && e.target.value !== data.title && updateMeta({ title: e.target.value.trim() })} disabled={approved} aria-label="Prompt title" />
        <div className="head-row">
          <TargetChips targets={boot.targets} value={data.targetId} onChange={(id) => updateMeta({ targetId: id })} disabled={approved || busy} />
          <ModeToggle value={data.mode} onChange={(m) => updateMeta({ mode: m })} disabled={approved || busy} compact />
          <div className="spacer" />
          <span className={`provider-badge ${provider}`} title={provider === 'mock' ? 'Offline mock optimizer: nothing is sent anywhere and nothing is billed.' : `Gemini model ${boot.settings.model}`}>
            {provider === 'mock' ? 'Mock · offline · $0' : `Gemini · ${boot.settings.model}`}
          </span>
          <button className="btn primary" disabled={approved || busy} onClick={() => startGeneration('generate')} data-testid="generate">
            {busy ? 'Working…' : data.versions.length > 1 ? 'Regenerate from original' : 'Generate'}
          </button>
        </div>
      </div>

      {approved && (
        <div className="approved-bar" data-testid="approved-bar">
          <span>
            ✔ Approved version {data.versions.find((v) => v.id === data.approvedVersionId)?.seq} · {fmtTime(data.approvals[0]?.approvedAt ?? data.updatedAt)}
          </span>
          <div className="spacer" />
          <button className="btn primary" onClick={() => copy('approved')} data-testid="copy-approved">
            Copy final prompt
          </button>
          <button className="btn" onClick={() => call('external:openTarget', { targetId: data.targetId }).catch((e) => notify(e.message, 'error'))} data-testid="open-target">
            Open {target.name}
          </button>
          <button className="btn" onClick={() => call<string | null>('export:prompt', { sessionId }).then((p) => p && notify(`Exported to ${p}`, 'ok'))}>
            Export…
          </button>
          <button className="btn ghost" onClick={() => call('sessions:reopen', { id: sessionId }).then(load).then(onChanged)}>
            Reopen for editing
          </button>
        </div>
      )}

      <div className="session-body">
        <div className="center">
          <div className="tabs">
            <button className={tab === 'draft' ? 'on' : ''} onClick={() => setTab('draft')} data-testid="tab-draft">
              Draft
            </button>
            <button className={tab === 'original' ? 'on' : ''} onClick={() => setTab('original')} data-testid="tab-original">
              Original (locked)
            </button>
            <button className={tab === 'compare' ? 'on' : ''} onClick={() => { setCompareLeft(undefined); setTab('compare'); }} data-testid="tab-compare">
              Compare versions
            </button>
            <div className="spacer" />
            {tab === 'draft' && (
              <span className={`save-state ${saveState}`} data-testid="save-state">
                {saveState === 'saved' ? 'All changes saved' : saveState === 'saving' ? 'Saving…' : 'Unsaved'}
              </span>
            )}
          </div>

          {tab === 'draft' && (
            <>
              <Editor value={working} readOnly={approved || busy} highlights={highlights} onChange={onEdit} onSelection={setSel} handleRef={editorRef} testId="draft-editor" />
              {!approved && (
                <div className="action-bar">
                  <input className="grow" placeholder="Revision instruction for Gemini (optional if you added comments)…" value={instruction} onChange={(e) => setInstruction(e.target.value)} data-testid="revise-instruction" />
                  <button className="btn" disabled={!sel} onClick={() => setRight('comments')} title="Attach a comment to the highlighted text" data-testid="comment-selection">
                    Comment on selection
                  </button>
                  <button className="btn" disabled={busy || !sel} onClick={() => startGeneration('revise', sel)} title="Revise only the highlighted passage" data-testid="revise-selection">
                    Revise selection
                  </button>
                  <button className="btn" disabled={busy || data.versions.length < 2} onClick={() => startGeneration('revise')} data-testid="revise-all">
                    Revise whole prompt{openComments.length ? ` (${openComments.length} comments)` : ''}
                  </button>
                  <button className="btn ghost" onClick={checkpoint} title="Ctrl+S" data-testid="save-version">
                    Save version
                  </button>
                  <button className="btn approve" disabled={busy || data.versions.length < 2} onClick={approve} data-testid="approve">
                    Approve…
                  </button>
                </div>
              )}
              {!approved && data.versions.length >= 2 && (
                <div className="action-bar subtle">
                  <button className="btn small ghost" onClick={() => copy('working')}>
                    Copy current draft
                  </button>
                  <span className="hint">Select text in the draft to comment on it or revise only that passage.</span>
                </div>
              )}
            </>
          )}
          {tab === 'original' && (
            <div className="original" data-testid="original-text">
              <div className="note">Your original instruction is stored unchanged and is always the basis for “Generate”.</div>
              <pre>{original}</pre>
            </div>
          )}
          {tab === 'compare' && <Compare versions={data.versions} workingText={working} onRestore={restore} readOnly={approved} initialLeft={compareLeft} />}
        </div>

        <aside className="right">
          <div className="tabs small">
            {(
              [
                ['comments', `Comments${openComments.length ? ` (${openComments.length})` : ''}`],
                ['recs', `Recommendations${pendingRecs ? ` (${pendingRecs})` : ''}`],
                ['insights', 'Insights'],
                ['rules', 'Rules'],
                ['history', `History (${data.versions.length})`],
                ...(data.projectId ? [['context', `Project files${picks.size ? ` (${picks.size})` : ''}`]] : []),
              ] as [RightTab, string][]
            ).map(([k, label]) => (
              <button key={k} className={right === k ? 'on' : ''} onClick={() => setRight(k)} data-testid={`rt-${k}`}>
                {label}
              </button>
            ))}
          </div>
          <div className="right-body">
            {right === 'comments' && (
              <div className="panel">
                {!approved && (
                  <div className="comment-new">
                    {sel ? (
                      <>
                        <div className="quote">“{sel.text.length > 160 ? sel.text.slice(0, 160) + '…' : sel.text}”</div>
                        <textarea placeholder="Your comment on the highlighted text…" value={commentDraft} onChange={(e) => setCommentDraft(e.target.value)} data-testid="comment-input" />
                        <button className="btn small primary" disabled={!commentDraft.trim()} onClick={addComment} data-testid="comment-add">
                          Add comment
                        </button>
                      </>
                    ) : (
                      <div className="hint">Highlight text in the draft to attach a comment.</div>
                    )}
                  </div>
                )}
                {data.comments.length === 0 && <div className="hint">No comments yet.</div>}
                {[...data.comments].reverse().map((c) => {
                  const a = anchored.get(c.id);
                  return (
                    <div key={c.id} className={`comment ${c.status} ${activeComment === c.id ? 'active' : ''}`} data-testid="comment" onMouseEnter={() => setActiveComment(c.id)} onMouseLeave={() => setActiveComment(null)}>
                      <div className="quote" onClick={() => a && tab === 'draft' && editorRef.current?.select(a.start, a.end)}>
                        “{c.quote.length > 120 ? c.quote.slice(0, 120) + '…' : c.quote}”
                      </div>
                      <div className="body">{c.body}</div>
                      <div className="meta">
                        {fmtTime(c.createdAt)} · {c.status === 'resolved' ? 'Resolved' : a ? 'Open' : 'Open · text no longer in draft'}
                        {!approved && (
                          <button className="link" onClick={() => call('comments:update', { id: c.id, status: c.status === 'open' ? 'resolved' : 'open' }).then(load)}>
                            {c.status === 'open' ? 'Resolve' : 'Reopen'}
                          </button>
                        )}
                      </div>
                    </div>
                  );
                })}
              </div>
            )}

            {right === 'recs' && (
              <div className="panel" data-testid="recs-panel">
                <div className="note warn">Recommendations are Gemini's suggestions, not your instructions. Nothing here is in the prompt until you accept it, and accepted items are saved as a separate version.</div>
                {data.mode === 'preserve' && data.recommendations.length === 0 && <div className="hint">Preserve Intent mode makes no recommendations. Switch to Challenge &amp; Redesign to get them.</div>}
                {data.recommendations.map((r) => (
                  <div key={r.id} className={`rec ${r.status}`} data-testid="rec">
                    <div className="rec-head">
                      <span className="tag">Recommended</span> <strong>{r.title}</strong>
                      <span className={`status ${r.status}`}>{r.status}</span>
                    </div>
                    <div className="rationale">{r.rationale}</div>
                    {r.findText && (
                      <div className="diffline">
                        <span className="diff-del">{r.findText}</span>
                      </div>
                    )}
                    <div className="diffline">
                      <span className="diff-add">{r.replacementText}</span>
                    </div>
                    {r.status === 'pending' && !approved && (
                      <div className="row">
                        <button className="btn small primary" onClick={() => decideRec(r.id, 'accepted')} data-testid="rec-accept">
                          Accept into draft
                        </button>
                        <button className="btn small ghost" onClick={() => decideRec(r.id, 'rejected')}>
                          Reject
                        </button>
                      </div>
                    )}
                  </div>
                ))}
              </div>
            )}

            {right === 'insights' && (
              <div className="panel" data-testid="insights">
                {!latestOk && <div className="hint">Generate a draft to see what changed and why.</div>}
                {data.generations.slice(0, 1).map((g) => (
                  <div key={g.id}>
                    <h4>Latest run · {g.kind === 'generate' ? 'Generation' : 'Revision'} · {fmtTime(g.createdAt)}</h4>
                    <div className="kv">
                      <span>Status</span>
                      <span className={g.status}>{g.status}{g.error ? ` — ${g.error}` : ''}</span>
                      <span>Engine</span>
                      <span>{g.provider === 'mock' ? 'Offline mock (no cost)' : `Gemini ${g.model}`}</span>
                      <span>Cost</span>
                      <span>{g.costUsd === null ? '—' : usd(g.costUsd, 4)}</span>
                    </div>
                    {g.conflicts.length > 0 && (
                      <>
                        <h4 className="warn-text">Conflicts with your rules</h4>
                        {g.conflicts.map((c: any, i: number) => (
                          <div key={i} className="note warn">
                            <strong>{c.ruleTitle}</strong>: {c.issue}
                            <br />
                            <em>Suggestion: {c.suggestion}</em>
                          </div>
                        ))}
                      </>
                    )}
                    {g.questions.length > 0 && (
                      <>
                        <h4>Open questions</h4>
                        <ul>{g.questions.map((q, i) => <li key={i}>{q}</li>)}</ul>
                      </>
                    )}
                    {g.changes.length > 0 && (
                      <>
                        <h4>What changed</h4>
                        <ul>{g.changes.map((c: any, i: number) => <li key={i}><strong>{c.kind}:</strong> {c.description}</li>)}</ul>
                      </>
                    )}
                    {g.transmissions.length > 0 && (
                      <>
                        <h4>Sent to Gemini</h4>
                        <ul>{g.transmissions.map((t, i) => <li key={i}>{t.label} ({t.chars.toLocaleString()} chars)</li>)}</ul>
                      </>
                    )}
                  </div>
                ))}
              </div>
            )}

            {right === 'rules' && (
              <div className="panel" data-testid="rules-panel">
                <h4>Rules for the next generation</h4>
                <RuleList rules={data.applicableRules.map((r) => ({ title: r.title, scope: r.scope, protected: r.protected, version: r.version }))} />
                <h4>Applied to the latest draft</h4>
                {latestOk ? <RuleList rules={latestOk.rules} /> : <div className="hint">No draft generated yet.</div>}
                <div className="hint">Manage rules in the Instruction Library. Protected rules are appended word-for-word by the app, so the optimizer cannot weaken them.</div>
              </div>
            )}

            {right === 'history' && (
              <div className="panel" data-testid="history">
                {[...data.versions].reverse().map((v) => (
                  <div key={v.id} className={`version ${v.id === data.approvedVersionId ? 'approved' : ''}`} data-testid="version">
                    <div>
                      <strong>v{v.seq}</strong> · {KIND_LABEL[v.kind] ?? v.kind} {v.id === data.approvedVersionId && <span className="tag ok">approved</span>}
                    </div>
                    <div className="meta">{v.note}</div>
                    <div className="meta">{fmtTime(v.createdAt)}</div>
                    <div className="row">
                      <button className="link" onClick={() => { setCompareLeft(v.id); setTab('compare'); }}>
                        Compare with current
                      </button>
                      {!approved && v.seq > 1 && (
                        <button className="link" onClick={() => restore(v.id)}>
                          Restore
                        </button>
                      )}
                    </div>
                  </div>
                ))}
              </div>
            )}

            {right === 'context' && data.projectId && <ContextPanel projectId={data.projectId} picks={picks} setPicks={setPicks} notify={notify} />}
          </div>
        </aside>
      </div>

      {review && <ReviewModal preview={review} onCancel={() => setReview(null)} onConfirm={() => runPreview(review.previewId)} />}
    </div>
  );
}

function RuleList({ rules }: { rules: { title: string; scope: string; protected: boolean; version: number }[] }) {
  if (rules.length === 0) return <div className="hint">No rules apply.</div>;
  return (
    <ul className="rule-list">
      {rules.map((r, i) => (
        <li key={i}>
          {r.protected && <span className="tag prot">protected</span>} <span className="tag">{r.scope}</span> {r.title} <span className="meta">v{r.version}</span>
        </li>
      ))}
    </ul>
  );
}

function ContextPanel({ projectId, picks, setPicks, notify }: { projectId: string; picks: Set<string>; setPicks(p: Set<string>): void; notify: Props['notify'] }) {
  const [folders, setFolders] = useState<Folder[]>([]);
  const [files, setFiles] = useState<Record<string, FileEntry[]>>({});
  const [filter, setFilter] = useState('');
  const [preview, setPreview] = useState<{ key: string; text: string; findings: string[] } | null>(null);

  const loadFiles = useCallback(
    async (f: Folder) => {
      try {
        const list = await call<FileEntry[]>('folders:files', { folderId: f.id });
        setFiles((m) => ({ ...m, [f.id]: list }));
      } catch (e: any) {
        notify(e.message, 'error');
      }
    },
    [notify],
  );

  useEffect(() => {
    call<Folder[]>('folders:list', { projectId })
      .then((fs) => {
        setFolders(fs);
        fs.forEach((f) => void loadFiles(f));
      })
      .catch((e) => notify(e.message, 'error'));
  }, [projectId, notify, loadFiles]);

  const toggle = (key: string) => {
    const n = new Set(picks);
    if (n.has(key)) n.delete(key);
    else n.add(key);
    setPicks(n);
  };

  const show = async (folderId: string, rel: string) => {
    const key = `${folderId}|${rel}`;
    try {
      const r = await call<{ text: string; truncated: boolean; findings: string[] }>('folders:preview', { folderId, relPath: rel });
      setPreview({ key, text: r.text + (r.truncated ? '\n… (truncated)' : ''), findings: r.findings });
    } catch (e: any) {
      notify(e.message, 'error');
    }
  };

  return (
    <div className="panel" data-testid="context-panel">
      <div className="note">Read-only. Files you tick are shown to you for review before anything is sent to Gemini. Text inside files is treated as untrusted reference material.</div>
      {folders.length === 0 && <div className="hint">No folders are authorized for this project. Add one from the project settings in the sidebar.</div>}
      {folders.length > 0 && <input placeholder="Filter files…" value={filter} onChange={(e) => setFilter(e.target.value)} />}
      {folders.map((f) => (
        <div key={f.id} className="folder">
          <div className="folder-head">
            <span title={f.path}>📁 {f.path}</span>
            {!files[f.id] && (
              <button className="link" onClick={() => loadFiles(f)} data-testid="load-files">
                Browse
              </button>
            )}
          </div>
          {files[f.id] && (
            <div className="file-list">
              {files[f.id]
                .filter((x) => !filter || x.rel.toLowerCase().includes(filter.toLowerCase()))
                .slice(0, 400)
                .map((x) => {
                  const key = `${f.id}|${x.rel}`;
                  return (
                    <div key={x.rel} className={`file ${x.restricted ? 'restricted' : ''}`} title={x.restricted ?? `${(x.size / 1024).toFixed(1)} KB`} data-testid="file-row">
                      <input type="checkbox" disabled={!!x.restricted} checked={picks.has(key)} onChange={() => toggle(key)} aria-label={x.rel} />
                      <span className="name">{x.rel}</span>
                      {x.restricted ? <span className="tag prot">blocked</span> : <button className="link" onClick={() => show(f.id, x.rel)}>view</button>}
                    </div>
                  );
                })}
            </div>
          )}
        </div>
      ))}
      {preview && (
        <div className="file-preview">
          <div className="row">
            <strong>{preview.key.split('|')[1]}</strong>
            <div className="spacer" />
            <button className="link" onClick={() => setPreview(null)}>close</button>
          </div>
          {preview.findings.length > 0 && <div className="note warn">Possible credentials detected ({preview.findings.join(', ')}). This file will be blocked from sending.</div>}
          <pre>{preview.text}</pre>
        </div>
      )}
    </div>
  );
}
